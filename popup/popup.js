(function () {
  const { STORAGE_KEYS, LANGUAGES, CAPTION_MODES, I18N, getSettings, setSettings, getCurrentUiLang, setCurrentUiLang } = window.SM;

  let uiLang = getCurrentUiLang();
  let settings = null;

  const $ = (id) => document.getElementById(id);

  function t(key) { return I18N[uiLang][key]; }

  function fillLangOptions(select, selectedCode) {
    select.innerHTML = '';
    for (const lang of LANGUAGES) {
      const opt = document.createElement('option');
      opt.value = lang.code;
      opt.textContent = uiLang === 'zh' ? lang.zh : lang.en;
      if (lang.code === selectedCode) opt.selected = true;
      select.appendChild(opt);
    }
  }

  function fillModeOptions(select, selected) {
    select.innerHTML = '';
    const modes = [
      { value: CAPTION_MODES.TRANSLATE, label: I18N[uiLang].modeTranslate },
      { value: CAPTION_MODES.AUTO_GENERATED, label: I18N[uiLang].modeAutoGenerated },
    ];
    for (const m of modes) {
      const opt = document.createElement('option');
      opt.value = m.value;
      opt.textContent = m.label;
      if (m.value === selected) opt.selected = true;
      select.appendChild(opt);
    }
  }

  function applyUI() {
    const i18n = I18N[uiLang];
    $('extName').textContent = i18n.name;
    $('lblAutoCaptions').textContent = i18n.autoCaptions;
    $('lblCaptionMode').textContent = i18n.captionMode;
    $('lblTargetLang').textContent = i18n.targetLang;
    $('lblTargetLangHint').textContent = i18n.targetLangHint;
    $('lblAutoYt').textContent = i18n.autoOnYt;
    $('lblAutoReload').textContent = i18n.autoReloadOnFail;
    document.documentElement.lang = uiLang === 'zh' ? 'zh-CN' : 'en';

    const toggle = $('toggleAuto');
    toggle.setAttribute('aria-checked', String(settings[STORAGE_KEYS.AUTO_CAPTIONS]));

    fillModeOptions($('captionMode'), settings[STORAGE_KEYS.CAPTION_MODE]);
    fillLangOptions($('targetLang'), settings[STORAGE_KEYS.TARGET_LANG]);
    // Target language only applies in auto-translate mode.
    const translateMode = settings[STORAGE_KEYS.CAPTION_MODE] === CAPTION_MODES.TRANSLATE;
    $('targetLang').disabled = !translateMode;
    $('targetLang').classList.toggle('disabled', !translateMode);
    $('lblTargetLangHint').style.visibility = translateMode ? 'visible' : 'hidden';
    $('chkAutoYt').checked = settings[STORAGE_KEYS.AUTO_ON_YT];
    $('chkAutoReload').checked = settings[STORAGE_KEYS.AUTO_RELOAD_ON_FAIL];
  }

  async function save(patch) {
    Object.assign(settings, patch);
    await setSettings(patch);
    const hint = $('savedHint');
    hint.textContent = t('saved');
    hint.classList.add('show');
    setTimeout(() => hint.classList.remove('show'), 1400);
    // Notify content scripts about the change.
    chrome.runtime.sendMessage({ type: 'SM_SETTINGS_CHANGED', settings }).catch(() => {});
  }

  function bindEvents() {
    $('toggleAuto').addEventListener('click', () => {
      const next = !settings[STORAGE_KEYS.AUTO_CAPTIONS];
      save({ [STORAGE_KEYS.AUTO_CAPTIONS]: next });
      applyUI();
    });

    $('captionMode').addEventListener('change', (e) => {
      save({ [STORAGE_KEYS.CAPTION_MODE]: e.target.value });
      applyUI();
    });

    $('targetLang').addEventListener('change', (e) =>
      save({ [STORAGE_KEYS.TARGET_LANG]: e.target.value }));

    $('chkAutoYt').addEventListener('change', (e) =>
      save({ [STORAGE_KEYS.AUTO_ON_YT]: e.target.checked }));

    $('chkAutoReload').addEventListener('change', (e) =>
      save({ [STORAGE_KEYS.AUTO_RELOAD_ON_FAIL]: e.target.checked }));

    $('langSwitch').addEventListener('click', () => {
      uiLang = uiLang === 'en' ? 'zh' : 'en';
      setCurrentUiLang(uiLang);
      applyUI();
    });
  }

  async function init() {
    settings = await getSettings();
    $('logo').src = chrome.runtime.getURL('icons/icon48.png');
    bindEvents();
    applyUI();
  }

  init();
})();
